"""Rasterise Inter (SIL OFL) into run-length glyph spans for the Worker's PNG
renderer. Run once: python3 scripts/gen-font.py /path/to/Inter.ttf > src/font.ts
"""
import base64, json, struct, sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1]
ASCII = "".join(chr(c) for c in range(32, 127)) + "…·–"
SETS = {
    # name: (size, weight, chars)
    "big": (150, 700, "0123456789,"),
    "h1": (42, 600, ASCII),
    "h2": (30, 600, ASCII),
    "body": (23, 400, ASCII),
}

def font(size, weight):
    f = ImageFont.truetype(TTF, size)
    axes = f.get_variation_axes()
    vals = []
    for a in axes:
        n = a.get("name", b"")
        n = n.decode() if isinstance(n, bytes) else n
        if n.lower().startswith("weight") or n == "wght":
            vals.append(weight)
        elif n.lower().startswith("optical") or n == "opsz":
            vals.append(min(max(size, a["minimum"]), a["maximum"]))
        else:
            vals.append(a["default"])
    f.set_variation_by_axes(vals)
    return f

out = {}
for name, (size, weight, chars) in SETS.items():
    f = font(size, weight)
    glyphs = {}
    for ch in chars:
        adv = f.getlength(ch)
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        runs = []
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            px = list(im.getdata())
            for yy in range(h):
                row = [min(3, (v + 42) // 85) for v in px[yy * w:(yy + 1) * w]] + [-1]
                start, cur = 0, 0
                for xx, a in enumerate(row):
                    if a != cur:
                        if cur > 0:
                            runs += [yy, start, xx - start, cur]
                        cur, start = a, xx
        data = base64.b64encode(struct.pack("<%dh" % len(runs), *runs)).decode()
        glyphs[ch] = [round(adv * 4) / 4, x0, y0, data]
    out[name] = {"g": glyphs}

print("// Generated by scripts/gen-font.py from Inter (SIL Open Font License 1.1).")
print("// Per glyph: [advance, xOffset, yOffset (from baseline), base64 int16 LE runs of (row, x, len, alpha 1-3)]")
print("export type GlyphSet = { g: Record<string, [number, number, number, string]> };")
print("export const FONTS: Record<\"big\" | \"h1\" | \"h2\" | \"body\", GlyphSet> = " + json.dumps(out, ensure_ascii=True, separators=(",", ":")) + ";")
